#!/usr/bin/env node
// Generates client/vendor/open-peeps.js: the Open Peeps avatar parts (design by Pablo Stanley, CC0 1.0)
// as plain SVG templates for the avatar builder. The parts come from DiceBear's @dicebear/open-peeps
// package (code MIT, design CC0). Each part is turned into a string with three colour placeholders
// (@S@ skin, @C@ clothing, @H@ hair), so the browser needs no library: it only substitutes colours
// and stacks the layers.
//
//   npm i --no-save @dicebear/open-peeps@9.4.2 @dicebear/core@9.4.2
//   node scripts/generate-avatar-parts.mjs            (PEEPS_DIR=<path to the package> to override)
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const packageDir = path.resolve(process.env.PEEPS_DIR || path.join(root, 'node_modules/@dicebear/open-peeps'));
const lib = pathToFileURL(path.join(packageDir, 'lib')).href;
const components = await import(`${lib}/components/index.js`);
const style = await import(`${lib}/index.js`);
const version = JSON.parse(fs.readFileSync(path.join(packageDir, 'package.json'), 'utf8')).version;

const PLACEHOLDER = { skin:'@S@', clothing:'@C@', headContrast:'@H@' };
const render = fn => fn({}, PLACEHOLDER);

// The static torso (outline, neck, shirt) comes out of the style's own template, so it stays exact.
const stubPrng = { pick: (values, fallback) => (values && values.length ? values[0] : fallback), bool: () => false };
const created = style.create({ prng:stubPrng, options:{
  skinColor:['SKINPH'], clothingColor:['CLOTHPH'], headContrastColor:['HAIRPH'],
  head:['short1'], face:['smile'], facialHairProbability:0, maskProbability:0, accessoriesProbability:0,
} });
const body = created.body;
const headStart = body.indexOf('<g transform="matrix(.99789 0 0 1 156 62)">');
if (headStart < 0) throw new Error('Open Peeps layout changed: head group not found');
const torso = body.slice(0, headStart).replaceAll('#SKINPH', '@S@').replaceAll('#CLOTHPH', '@C@');
const layout = {};
for (const match of body.matchAll(/<g transform="([^"]+)">/g)) layout[`g${Object.keys(layout).length}`] = match[1];
const transforms = [...body.matchAll(/<g transform="([^"]+)">/g)].map(match => match[1]);
// Order in the style: head, face, facialHair, mask, accessories.
const names = ['head', 'face', 'facialHair', 'mask', 'accessories'];
const layers = Object.fromEntries(names.map((name, index) => [name, transforms[index]]));

const parts = {};
for (const group of ['head', 'face', 'facialHair', 'accessories']) {
  parts[group] = Object.fromEntries(Object.entries(components[group]).map(([name, fn]) => [name, render(fn)]));
}
const hairColoured = Object.entries(parts.head).filter(([, svg]) => svg.includes('@H@')).map(([name]) => name);

const schema = style.schema.properties;
const data = {
  viewBox:'0 0 704 704', layers, torso, ...parts, hairColoured,
  colors:{
    skin:schema.skinColor.default, clothing:schema.clothingColor.default, hair:schema.headContrastColor.default,
  },
};

const header = `/*
 * Open Peeps avatar parts for the Vaultlix avatar builder.
 * Design: Open Peeps by Pablo Stanley (https://www.openpeeps.com/), CC0 1.0 (public domain dedication,
 *   https://creativecommons.org/publicdomain/zero/1.0/).
 * Packaging: DiceBear @dicebear/open-peeps ${version} (MIT, https://github.com/dicebear/dicebear).
 * Generated by scripts/generate-avatar-parts.mjs. Do not edit by hand.
 */
`;
const output = `${header}window.VaultlixPeeps=${JSON.stringify(data)};\n`;
fs.writeFileSync(path.join(root, 'client/vendor/open-peeps.js'), output);
console.log(`client/vendor/open-peeps.js: ${(output.length / 1024).toFixed(0)} KB`,
  Object.fromEntries(Object.entries(parts).map(([group, items]) => [group, Object.keys(items).length])),
  `hair-coloured heads: ${hairColoured.length}`);
